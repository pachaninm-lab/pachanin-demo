import { IsNotEmpty, IsString, MaxLength } from 'class-validator';

/**
 * Причина блокировки организации.
 *
 * Значение попадает в запись аудита и оттуда — в CSV-выгрузку журнала, которую
 * открывает другой человек: комплаенс-офицер или регулятор. Исполнение формулы
 * в этой выгрузке закрыто отдельно, кодировщиком ячейки; здесь закрывается
 * вторая половина V1.3.3 — длина. Инлайн-тип объявлял поле обязательным, но
 * стирался, поэтому обязательным оно не было: пустое тело давало запись
 * блокировки без причины.
 */
export class BlockOrganizationDto {
  @IsString()
  @IsNotEmpty()
  @MaxLength(1000)
  reason!: string;
}
