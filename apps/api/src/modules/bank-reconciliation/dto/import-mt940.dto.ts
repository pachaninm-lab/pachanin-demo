import { IsNotEmpty, IsString, MaxLength } from 'class-validator';

/**
 * Импорт банковской выписки MT940.
 *
 * Сервис приводит через String(content ?? '').trim() и отвергает пустую
 * выписку, поэтому не-строка живым дефектом не была. Чего у него не было —
 * верхней границы: выписка разбирается построчно, и ничто в самом обработчике
 * не ограничивало её размер.
 *
 * 4 МБ выбраны не наугад: настоящая MT940 за месяц — это десятки килобайт,
 * так что запас здесь трёхзначный, а не двукратный. Это вторая половина
 * V1.3.3 — обрезание слишком длинного ввода — на маршруте, который работает
 * с деньгами.
 */
export class ImportMt940Dto {
  @IsString()
  @IsNotEmpty()
  @MaxLength(4 * 1024 * 1024)
  content!: string;
}
