import { IsOptional, IsString, MaxLength, MinLength } from 'class-validator';

/**
 * Предел размера выписки — 8 МиБ.
 *
 * Не догадка о «нормальном» размере, а граница разбора: `parseMT940` делит всё
 * содержимое на строки и держит их в памяти целиком. Без предела размер
 * определяется только настройкой парсера тела запроса, то есть контуром,
 * который об этом разборе ничего не знает.
 */
export const STATEMENT_MAX_CHARS = 8 * 1024 * 1024;

/** Импорт выписки MT940. */
export class ImportStatementDto {
  @IsString({ message: 'Содержимое выписки должно быть строкой.' })
  @MinLength(1, { message: 'Пустая выписка не может быть импортирована.' })
  @MaxLength(STATEMENT_MAX_CHARS, { message: 'Выписка превышает предел разбора.' })
  content!: string;
}

/**
 * Ручная привязка строки выписки к сделке.
 *
 * `paymentId` — прежнее имя того же поля; обработчик принимает оба и берёт
 * первое непустое, поэтому обязательным не может быть ни одно из них по
 * отдельности. Проверка «хотя бы одно задано» живёт в сервисе: там же, где
 * решается, что именно считать идентификатором строки.
 */
export class ManualMatchDto {
  @IsOptional()
  @IsString({ message: 'Идентификатор строки выписки должен быть строкой.' })
  @MaxLength(128)
  entryId?: string;

  @IsOptional()
  @IsString({ message: 'Идентификатор платежа должен быть строкой.' })
  @MaxLength(128)
  paymentId?: string;

  @IsString({ message: 'Идентификатор сделки должен быть строкой.' })
  @MinLength(1, { message: 'Идентификатор сделки не может быть пустым.' })
  @MaxLength(128)
  dealId!: string;
}
