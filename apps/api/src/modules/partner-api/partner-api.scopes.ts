/**
 * Единственный источник правды о том, какие scope существуют у партнёрского API.
 *
 * Отдельный файл, а не константа в сервисе или в DTO. Первая версия правки
 * объявила список в DTO рядом с комментарием «политика scope остаётся в сервисе
 * и здесь не дублируется» — и тут же его продублировала. Найдено ревью, а не
 * чтением, и это настоящий дефект: добавление scope в сервисе без синхронной
 * правки DTO заставило бы `ValidationPipe` отклонять запросы, которые сервис
 * принимает, а удаление — наоборот, пропускать на уровень сервиса то, что он
 * отвергнет. Расхождение двух копий одного списка невозможно заметить по
 * одному файлу.
 *
 * Границы это не меняет: DTO проверяет форму на входе, сервис остаётся
 * авторитетом. Просто список у них теперь один.
 */
export const PARTNER_API_SCOPES = [
  'deals:read',
  'deals:write',
  'shipments:read',
  'documents:read',
  'payments:read',
] as const;

export type PartnerApiScope = (typeof PARTNER_API_SCOPES)[number];
