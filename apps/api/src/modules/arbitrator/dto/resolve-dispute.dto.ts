import { IsIn, IsInt, IsOptional, IsString, Max, MaxLength, Min, MinLength } from 'class-validator';

export const DISPUTE_OUTCOMES = ['BUYER_WINS', 'SELLER_WINS', 'SPLIT', 'CANCELLED'] as const;

export type DisputeOutcomeValue = (typeof DISPUTE_OUTCOMES)[number];

/**
 * Исход спора и, для раздела, доля покупателя.
 *
 * Всё это объявлялось инлайн-типом. Инлайн-тип стирается до `Object`,
 * ValidationPipe его не видит, и на удержании в 1 000 000 копеек замерено
 * следующее:
 *
 *   splitPct: 200      → возврат покупателю 2 000 000 — вдвое больше удержания
 *   splitPct: -50      → выплата продавцу 1 499 999 — полтора удержания
 *   splitPct: NaN      → RangeError из BigInt, 500 на пользовательском вводе
 *   splitPct: Infinity → то же
 *   splitPct: 1e30     → возврат 10^34 копеек
 *   splitPct: '50'     → строка проходит расчёт и доходит до записи в БД
 *   SPLIT без splitPct → деньги не двигаются, спор помечен RESOLVED,
 *                        удержание заперто навсегда
 *   произвольный outcome → то же самое, плюс произвольный исход в БД
 *
 * Колонка `outcome` в схеме — обычный `String?`, поэтому ниже по течению
 * произвольный исход тоже никто не ловит.
 *
 * Здесь проверяется ФОРМА полей. Связь между ними — раздел требует долю, а
 * прочие исходы её запрещают — проверяется в сервисе: вызывающий в обход
 * границы не должен уметь сдвинуть деньги на непроверенной доле.
 */
export class ResolveDisputeDto {
  @IsIn(DISPUTE_OUTCOMES, {
    message: `Исход спора должен быть одним из: ${DISPUTE_OUTCOMES.join(', ')}.`,
  })
  outcome!: DisputeOutcomeValue;

  /**
   * Доля покупателя в процентах, целое от 0 до 100.
   *
   * `@Type(() => Number)` здесь нет намеренно: он выполняется ДО проверок и
   * превратил бы строку в число, то есть пропустил бы ровно тот вход, который
   * замер поймал. `@IsInt` без него отклоняет и строку, и NaN, и Infinity.
   *
   * Дробное значение отклоняется, а не усекается молча: молчаливое изменение
   * доли в денежном расчёте и есть тот класс дефекта, от которого это поле
   * защищают. Прежний `Math.trunc` именно это и делал.
   */
  @IsOptional()
  @IsInt({ message: 'Доля покупателя должна быть целым числом процентов.' })
  @Min(0, { message: 'Доля покупателя не может быть отрицательной.' })
  @Max(100, { message: 'Доля покупателя не может превышать 100 процентов.' })
  splitPct?: number;

  @IsString({ message: 'Основание решения должно быть строкой.' })
  @MinLength(1, { message: 'Основание решения не может быть пустым.' })
  @MaxLength(2000)
  reason!: string;
}
