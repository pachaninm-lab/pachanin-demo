import { IsInt, IsString, Max, MaxLength, Min, MinLength } from 'class-validator';

/**
 * Сумма, запрашиваемая в факторинг.
 *
 * Целые копейки. Верхняя граница — не круглое число «на глаз», а предел, за
 * которым целочисленная арифметика в JavaScript начинает молча терять точность:
 * выше Number.MAX_SAFE_INTEGER сумма перестаёт быть той суммой, которую ввели.
 */
export const REQUESTED_AMOUNT_MAX_KOPECKS = Number.MAX_SAFE_INTEGER;

/**
 * Заявка на факторинг.
 *
 * Тело объявлялось инлайн-типом, который стирается до `Object`, и сумма уходила
 * прямо в `Math.round(requestedAmountKopecks * approvedPct)`. Замерено: при
 * рейтинге, дающем автоматическое одобрение, заявка получала статус APPROVED на
 * ЛЮБОМ входе —
 *
 *   NaN            → approvedAmountKopecks: NaN, в JSON `null`  — одобрено без суммы
 *   поле опущено   → то же самое
 *   Infinity       → в JSON `null`                              — одобрено без суммы
 *   -1 000 000     → одобрено на отрицательную сумму
 *   1e300          → одобрено на 1e+300 копеек
 *   '1000000'      → строка прошла молча
 *   { valueOf }    → объект приведён к числу и прошёл
 *
 * Одобренная заявка без суммы — это не отказ и не ошибка, а решение о
 * финансировании, у которого нет числа; именно в таком виде оно и возвращалось
 * вызывающему.
 */
export class CreateFactoringApplicationDto {
  @IsString({ message: 'Идентификатор сделки должен быть строкой.' })
  @MinLength(1, { message: 'Идентификатор сделки не может быть пустым.' })
  @MaxLength(128)
  dealId!: string;

  @IsString({ message: 'Идентификатор организации должен быть строкой.' })
  @MinLength(1, { message: 'Идентификатор организации не может быть пустым.' })
  @MaxLength(128)
  organizationId!: string;

  /**
   * Проверка на принадлежность к списку подключённых факторов остаётся в
   * сервисе: она уже есть, отказывает закрыто и отвечает 403, а не 400.
   * Дублировать её здесь значило бы тихо поменять код ответа.
   */
  @IsString({ message: 'Наименование фактора должно быть строкой.' })
  @MinLength(1, { message: 'Наименование фактора не может быть пустым.' })
  @MaxLength(200)
  factorName!: string;

  /**
   * `@Type(() => Number)` здесь нет намеренно: он выполняется ДО проверок и
   * пропустил бы и строку, и объект с `valueOf`, то есть ровно те входы,
   * которые замер поймал.
   */
  @IsInt({ message: 'Запрашиваемая сумма должна быть целым числом копеек.' })
  @Min(1, { message: 'Запрашиваемая сумма должна быть положительной.' })
  @Max(REQUESTED_AMOUNT_MAX_KOPECKS, {
    message: 'Запрашиваемая сумма превышает предел точного целочисленного представления.',
  })
  requestedAmountKopecks!: number;
}
