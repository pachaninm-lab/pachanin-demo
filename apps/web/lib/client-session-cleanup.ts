/**
 * V14.3.1 — очистка клиентского хранилища при выходе.
 *
 * Серверный ответ на выход просит браузер очистить хранилище заголовком
 * `Clear-Site-Data`, и это основной механизм. Но он действует ТОЛЬКО в
 * защищённом контексте: по http браузер его игнорирует, а если запрос вообще
 * не дошёл — заголовка не будет. Запись ASVS называет именно этот пробел:
 * «требование также просит клиентский путь, который убирает за собой, когда
 * сервер при выходе недоступен, и такого пути нет».
 *
 * Поэтому здесь второй, независимый путь. Он вызывается в `finally` каждого
 * выхода — то есть и тогда, когда fetch упал.
 *
 * Чистится ВСЁ, а не список чувствительных ключей. Список пришлось бы
 * поддерживать вручную, и любой новый компонент, начавший писать в хранилище,
 * тихо оказался бы вне его — deny by default здесь дешевле и надёжнее. Цена
 * названа честно: тема и плотность интерфейса сбрасываются к умолчанию. На
 * общем или одолженном устройстве это скорее правильное поведение, чем потеря.
 *
 * Синхронно намеренно: сразу после выхода идёт навигация, и асинхронная уборка
 * могла бы не успеть. `caches` и регистрации service worker здесь не трогаются
 * по той же причине — их снимает `Clear-Site-Data` в production, а на
 * следующей загрузке подчищает V7CacheGuard.
 */
export function clearClientSessionState(): void {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.clear();
  } catch {
    // Хранилище может быть недоступно (приватный режим, отключённые site data).
    // Выход из-за этого падать не должен.
  }
  try {
    window.sessionStorage.clear();
  } catch {
    // То же самое.
  }
}
