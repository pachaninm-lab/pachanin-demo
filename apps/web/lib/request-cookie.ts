/**
 * Один разбор заголовка `Cookie` на всё приложение.
 *
 * До этого их было два, и они отвечали по-разному на один и тот же заголовок.
 * Это измерено, а не выведено. Для `Cookie: pc_csrf_token=AAA; pc_csrf_token=BBB`:
 *
 *   server-request-security.readCookie  →  "AAA"   (первое совпадение, .find)
 *   next RequestCookies.get / getAll    →  "BBB"   (последнее: Map по имени)
 *
 * То есть `assertCsrf` сверял бы заголовок с одним значением, а маршрут
 * `staff/open-cabinet` — с другим, при одном и том же запросе. Ровно это и
 * называется загрязнением параметров: два разбора одного входа расходятся, и
 * решение о доступе зависит от того, чей разбор сработал.
 *
 * Продублировать куку своими Set-Cookie платформа не может: и
 * `auth-cookies.ts`, и клиентская установка в `api/auth/demo/instant` пишут
 * host-only с `Path=/`, поэтому повтор всегда затирает, а не добавляет.
 * Второй `pc_csrf_token` в заголовке означает, что его поставил кто-то ещё —
 * сосед по registrable domain. Он у платформы реальный: control-хост
 * `control.xn----8sbjf4befbjgs9b.xn--p1ai` — поддомен основного, так что
 * общий домен у них есть, и cookie tossing здесь не абстракция.
 *
 * Поэтому неоднозначность отклоняется, а не разрешается в чью-то пользу.
 * Выбрать «первое» или «последнее» нельзя безопасно: порядок в заголовке
 * задаёт браузер по длине пути и времени создания (RFC 6265 §5.4), а время
 * создания подконтрольно тому, кто ставит куку. При двух значениях
 * возвращается пустая строка, и проверка отказывает — как при отсутствующей
 * куке. Легального запроса это не задевает: у него значение ровно одно.
 */

/**
 * Значение куки `name`, если оно в запросе ровно одно.
 *
 * Пустая строка означает «использовать нечего» во всех трёх случаях: куки нет,
 * её значение пустое, значений несколько или значение не декодируется. Вызов
 * решает сам, отказ это или нет; функция не бросает исключений.
 */
export function readRequestCookie(request: Request, name: string): string {
  const raw = request.headers.get('cookie');
  if (!raw) return '';

  const prefix = `${name}=`;
  let found = '';
  let matches = 0;

  // Несколько заголовков Cookie Headers.get() склеивает через '; ', поэтому
  // разбор по ';' видит и повтор внутри одного заголовка, и повтор между ними.
  for (const segment of raw.split(';')) {
    const item = segment.trim();
    if (!item.startsWith(prefix)) continue;
    matches += 1;
    if (matches > 1) return '';
    found = item.slice(prefix.length);
  }

  if (matches !== 1) return '';

  try {
    return decodeURIComponent(found);
  } catch {
    // decodeURIComponent бросает URIError на '%' и '%zz'. Раньше это исключение
    // уходило из обработчика маршрута наверх, и запрос с испорченной кукой
    // получал 500 вместо 403 — на всех маршрутах, где проверка стоит первой
    // строкой. Значение, которое не декодируется, — это не значение.
    return '';
  }
}
