export function dealText(text: string, locale: DealLocale, values: Readonly<Record<string, string | number>> = {}): string {
  const translated = locale !== 'ru' && Object.hasOwn(COPY, text) ? COPY[text][locale === 'en' ? 0 : 1] : text;
  return translated.replace(/\{([a-z]+)\}/g, (match, key: string) => Object.hasOwn(values, key) ? String(values[key]) : match);
}

