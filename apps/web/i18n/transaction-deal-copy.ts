export type DealLocale = 'ru' | 'en' | 'zh';

export function dealLocale(value: string | undefined): DealLocale {
  const language = value?.trim().toLowerCase().split(/[-_]/)[0];
  return language === 'en' || language === 'zh' ? language : 'ru';
}

