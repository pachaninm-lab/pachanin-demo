#!/usr/bin/env bash
set -Eeuo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
BASE_SCRIPT="$ROOT_DIR/scripts/release/production-like-kubernetes-outbox-runtime-base.sh"
GENERATED_SCRIPT="$ROOT_DIR/scripts/release/.production-like-kubernetes-outbox-runtime.generated.sh"
NAMESPACE="grainflow-acceptance"
DEFAULT_INSTALLED=0

if [[ ! -x "$BASE_SCRIPT" ]]; then
  echo "Missing executable base runtime acceptance script: $BASE_SCRIPT" >&2
  exit 2
fi

postgres_password="$(
  kubectl get secret grainflow-postgresql-secrets -n "$NAMESPACE" \
    -o jsonpath='{.data.POSTGRES_PASSWORD}' | base64 -d
)"
printf '::add-mask::%s\n' "$postgres_password"

admin_sql() {
  local sql="$1"
  kubectl exec -n "$NAMESPACE" statefulset/postgresql -- \
    env PGPASSWORD="$postgres_password" \
    psql -v ON_ERROR_STOP=1 -U postgres -d grainflow -Atc "$sql"
}

cleanup_acceptance_boundary() {
  rm -f "$GENERATED_SCRIPT"
  if [[ "$DEFAULT_INSTALLED" = "1" ]]; then
    admin_sql 'ALTER TABLE "outbox_entries" ALTER COLUMN "id" DROP DEFAULT;' >/dev/null || true
  fi
}
trap cleanup_acceptance_boundary EXIT

# Prisma's cuid() default is generated by Prisma Client, not PostgreSQL. The
# deep-runtime harness seeds synthetic rows through raw SQL, so it installs a
# disposable DB-side UUID default only for the duration of this acceptance run.
# Production schema and application ID semantics remain unchanged.
admin_sql "SELECT gen_random_uuid()::text;" >/dev/null
admin_sql 'ALTER TABLE "outbox_entries" ALTER COLUMN "id" SET DEFAULT gen_random_uuid()::text;' >/dev/null
DEFAULT_INSTALLED=1

# Patch only disposable acceptance assertions/probes. Production worker code,
# network policies and database schema remain unchanged.
BASE_SCRIPT="$BASE_SCRIPT" GENERATED_SCRIPT="$GENERATED_SCRIPT" node <<'NODE'
const fs = require('node:fs');
const source = fs.readFileSync(process.env.BASE_SCRIPT, 'utf8');

const gracefulBefore = '[[ "$graceful_row" == PENDING:::unsent || "$graceful_row" == DEAD_LETTER:::unsent ]]';
const gracefulAfter = [
  'IFS=\':\' read -r graceful_status graceful_current_owner graceful_current_token graceful_delivery <<< "$graceful_row"',
  'test "$graceful_delivery" = "unsent"',
  'if [[ "$graceful_status" = "PROCESSING" ]]; then',
  '  test -n "$graceful_current_owner"',
  '  test -n "$graceful_current_token"',
  '  test "$graceful_current_owner" != "$graceful_owner"',
  'else',
  '  [[ "$graceful_status" = "PENDING" || "$graceful_status" = "DEAD_LETTER" ]]',
  '  test -z "$graceful_current_owner"',
  '  test -z "$graceful_current_token"',
  'fi',
].join('\n');

const consumerBefore = [
  'kafka_pod="$(kubectl get pods -n "$NAMESPACE" -l app.kubernetes.io/name=kafka -o jsonpath=\'{.items[0].metadata.name}\')"',
  'set +e',
  'kubectl exec -n "$NAMESPACE" "pod/${kafka_pod}" -- \\',
  '  kafka-console-consumer \\',
  '    --bootstrap-server localhost:9092 \\',
  '    --topic grainflow.domain.events \\',
  '    --from-beginning \\',
  '    --timeout-ms 30000 \\',
  '    --property print.headers=true \\',
  '    --property print.value=false \\',
  '  > "$RUNTIME_DIR/kafka-backlog-consumer.log" 2> "$RUNTIME_DIR/kafka-backlog-consumer.stderr"',
  'consumer_status=$?',
  'set -e',
  '# Kafka console consumer exits non-zero on timeout after draining available records.',
  'test "$consumer_status" = "0" || test "$consumer_status" = "1"',
].join('\n');

const consumerAfter = [
  '# The hardened Kafka deployment exposes a loopback-only PROBE listener for broker-local evidence.',
  '# Using it avoids widening NetworkPolicy and avoids creating an additional network identity.',
  'kafka_pod="$(kubectl get pods -n "$NAMESPACE" -l app.kubernetes.io/name=kafka -o jsonpath=\'{.items[0].metadata.name}\')"',
  'set +e',
  'kubectl exec -n "$NAMESPACE" "pod/${kafka_pod}" -- \\',
  '  kafka-console-consumer \\',
  '    --bootstrap-server 127.0.0.1:19092 \\',
  '    --topic grainflow.domain.events \\',
  '    --from-beginning \\',
  '    --timeout-ms 30000 \\',
  '    --property print.headers=true \\',
  '    --property print.value=false \\',
  '  > "$RUNTIME_DIR/kafka-backlog-consumer.log" 2> "$RUNTIME_DIR/kafka-backlog-consumer.stderr"',
  'consumer_status=$?',
  'set -e',
  '# Kafka console consumer exits non-zero on timeout after draining available records.',
  'test "$consumer_status" = "0" || test "$consumer_status" = "1"',
].join('\n');

const finalLogsBefore = [
  'kubectl logs -n "$NAMESPACE" -l "$WORKER_SELECTOR" --all-containers=true --prefix=true --tail=1000 \\',
  '  > "$RUNTIME_DIR/final-worker-logs.txt" 2>&1',
].join('\n');

const finalLogsAfter = [
  'FAILURE_REASON="final outbox worker log collection was not stable after scale-down"',
  'terminating_workers=""',
  'active_workers=""',
  'for _ in $(seq 1 60); do',
  '  worker_snapshot="$(kubectl get pods -n "$NAMESPACE" -l "$WORKER_SELECTOR" -o json)"',
  '  terminating_workers="$(printf \'%s\' "$worker_snapshot" | jq \'[.items[] | select(.metadata.deletionTimestamp != null)] | length\')"',
  '  active_workers="$(printf \'%s\' "$worker_snapshot" | jq \'[.items[] | select(.metadata.deletionTimestamp == null)] | length\')"',
  '  if [[ "$terminating_workers" = "0" && "$active_workers" = "2" ]]; then',
  '    break',
  '  fi',
  '  sleep 1',
  'done',
  'test "$terminating_workers" = "0"',
  'test "$active_workers" = "2"',
  'mapfile -t final_worker_pods < <(',
  '  kubectl get pods -n "$NAMESPACE" -l "$WORKER_SELECTOR" \\',
  '    -o jsonpath=\'{range .items[*]}{.metadata.name}{"\\n"}{end}\' | sort',
  ')',
  'test "${#final_worker_pods[@]}" = "2"',
  ': > "$RUNTIME_DIR/final-worker-logs.txt"',
  'for pod in "${final_worker_pods[@]}"; do',
  '  kubectl logs -n "$NAMESPACE" "pod/${pod}" --all-containers=true --prefix=true --tail=1000 \\',
  '    >> "$RUNTIME_DIR/final-worker-logs.txt" 2>&1',
  'done',
  'FAILURE_REASON="final outbox worker logs contain forbidden runtime errors"',
].join('\n');

if (!source.includes(gracefulBefore)) {
  throw new Error('graceful shutdown assertion boundary not found');
}
if (!source.includes(consumerBefore)) {
  throw new Error('Kafka delivery probe boundary not found');
}
if (!source.includes(finalLogsBefore)) {
  throw new Error('final worker log collection boundary not found');
}

let rendered = source.replace(gracefulBefore, gracefulAfter);
rendered = rendered.replace(consumerBefore, consumerAfter);
rendered = rendered.replace(finalLogsBefore, finalLogsAfter);
if (
  rendered === source ||
  rendered.includes(gracefulBefore) ||
  rendered.includes(consumerBefore) ||
  rendered.includes(finalLogsBefore)
) {
  throw new Error('acceptance boundaries were not replaced exactly once');
}
fs.writeFileSync(process.env.GENERATED_SCRIPT, rendered, { mode: 0o700 });
NODE

bash "$GENERATED_SCRIPT"