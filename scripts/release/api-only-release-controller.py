def unbase64(value):
    demand(type(value) is str and 0 < len(value) <= 32768 and re.fullmatch(r'[A-Za-z0-9_-]+', value),
           'OIDC_ENCODING')
    return base64.urlsafe_b64decode(value + '=' * (-len(value) % 4))


def verify_workflow_identity(token, intent, now, *, keys=None):
    """Verify the GitHub-hosted current-main workflow, not a caller PASS flag.

    The audience commits to every intent byte, including digest, policy source,
    capacity and finite disposition. Production JWKS comes only from the fixed
    GitHub issuer over verified TLS; no caller key or alternate URL is accepted.
    Optional keys are dependency injection for native cryptographic tests.
    """
    demand(type(token) is str and len(token) <= 32768 and token.count('.') == 2, 'OIDC_TOKEN_REQUIRED')
    encoded_header, encoded_claims, encoded_signature = token.split('.')
    header, claims = closed_json(unbase64(encoded_header)), closed_json(unbase64(encoded_claims))
    demand(type(header) is dict and header.get('alg') == 'RS256' and header.get('typ') == 'JWT' and
           type(header.get('kid')) is str and len(header['kid']) <= 128 and
           not any(k in header for k in ('jku', 'x5u', 'jwk', 'crit')), 'OIDC_HEADER')
    if keys is None:
        class NoRedirect(urllib.request.HTTPRedirectHandler):
            def redirect_request(self, *args, **kwargs):
                return None
        url = 'https://token.actions.githubusercontent.com/.well-known/jwks'
        opener = urllib.request.build_opener(NoRedirect())
        with opener.open(urllib.request.Request(url, method='GET'), timeout=5) as response:
            demand(response.status == 200 and response.geturl() == url, 'OIDC_ISSUER_HTTP')
            keys = closed_json(response.read(1024 * 1024 + 1))
    demand(type(keys) is dict and type(keys.get('keys')) is list and len(keys['keys']) <= 32, 'OIDC_KEYS')
    selected = [k for k in keys['keys'] if type(k) is dict and k.get('kid') == header['kid']]
    demand(len(selected) == 1, 'OIDC_KEY_IDENTITY')
    key = selected[0]
    demand(key.get('kty') == 'RSA' and key.get('use') == 'sig' and key.get('alg') == 'RS256', 'OIDC_KEY_PROFILE')
    modulus = int.from_bytes(unbase64(key['n']), 'big')
    exponent = int.from_bytes(unbase64(key['e']), 'big')
    demand(2048 <= modulus.bit_length() <= 8192 and exponent == 65537, 'OIDC_RSA_PROFILE')
    signature = unbase64(encoded_signature)
    width = (modulus.bit_length() + 7) // 8
    demand(len(signature) == width and int.from_bytes(signature, 'big') < modulus, 'OIDC_SIGNATURE')
    recovered = pow(int.from_bytes(signature, 'big'), exponent, modulus).to_bytes(width, 'big')
    sha = hashlib.sha256((encoded_header + '.' + encoded_claims).encode('ascii')).digest()
    tail = bytes.fromhex('3031300d060960864801650304020105000420') + sha
    expected = b'\x00\x01' + b'\xff' * (width - len(tail) - 3) + b'\x00' + tail
    demand(hmac.compare_digest(recovered, expected), 'OIDC_SIGNATURE')
    fixed = {'iss': 'https://token.actions.githubusercontent.com',
             'aud': 'urn:pc-crop:api-only-release:4637:' + digest(intent),
             'repository': 'pachaninm-lab/pachanin-demo', 'repository_id': '1203022077',
             'repository_owner': 'pachaninm-lab', 'repository_owner_id': '263435807',
             'actor': 'pachaninm-lab', 'actor_id': '263435807', 'event_name': 'issue_comment',
             'ref': 'refs/heads/main', 'sha': intent['target_sha'],
             'workflow_ref': 'pachaninm-lab/pachanin-demo/.github/workflows/production-api-only-release.yml@refs/heads/main',
             'workflow_sha': intent['target_sha'], 'run_id': intent['run_id'],
             'run_attempt': '1', 'runner_environment': 'github-hosted'}
    demand(type(claims) is dict and all(claims.get(k) == v and type(claims.get(k)) is type(v)
                                      for k, v in fixed.items()), 'OIDC_CLAIM_BINDING')
    demand(all(type(claims.get(k)) is int for k in ('iat', 'nbf', 'exp')) and
           claims['iat'] - 30 <= now and claims['nbf'] - 30 <= now < claims['exp'] and
           0 < claims['exp'] - claims['iat'] <= 900, 'OIDC_TIME')
    return True



