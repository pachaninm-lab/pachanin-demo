def runner_action(action):
    runner_only()
    if action=='bind-window':
        validate_trigger(runner_file('api-only-command.json'),os.environ['COMMAND_ID'])
        pages=runner_file('api-only-authority.json')
        demand(type(pages) is list and len(pages)<=10 and all(type(p) is list for p in pages),'WINDOW_PAGINATION')
        claim=bind_window(sum(pages,[]),os.environ['TARGET_SHA'],os.environ['COMMAND_ID'],int(time.time()))
        path=Path(os.environ['RUNNER_TEMP'])/'api-only-claim.json'
        path.write_bytes(canonical(claim)+b'\n')
        return None
    if action=='baseline-publication':
        return acquire_baseline_publication(runner_file('api-only-baseline.json'))
    if action=='build-intent':
        return build_intent()
    if action=='identity-audience':
        return 'urn:pc-crop:api-only-release:4637:'+digest(runner_file('api-only-intent.json'))
    if action=='envelope':
        response=closed_json(os.environ['IDENTITY_RESPONSE'].encode())
        demand(type(response.get('value')) is str,'OIDC_TOKEN_REQUIRED')
        return {'intent':runner_file('api-only-intent.json'),'identity_token':response['value']}
    if action=='validate-result':
        value=runner_file('api-only-result.json')
        demand(value.get('schema')=='pc.api-only-release-result.v1' and
               value.get('target_sha')==os.environ['TARGET_SHA'] and
               value.get('result') in ('HOLD','ROLLED_BACK_API_IMAGE_ONLY','RECONCILIATION_REQUIRED',
                                      'API_IMAGE_RELEASE_VERIFIED') and
               value.get('deployment_authorized') is False,'TERMINAL_RESULT_NOT_PROVEN')
        return None
    raise ReleaseError('RUNNER_ACTION')

def protected_equal(before, after):
    return all(before[k] == after[k] for k in ('siblings', 'volumes', 'preservation'))


def verify_runtime(before, after, image_id, revision):
    demand(after['image_id'] == image_id and after['revision'] == revision and after['ready'] is True,
           'API_IMAGE_OR_READINESS_MISMATCH')
    demand(after['runtime_fingerprint'] == before['runtime_fingerprint'], 'API_CONFIGURATION_CHANGED')
    demand(protected_equal(before, after), 'PROTECTED_INVENTORY_CHANGED')


def release(intent, host, *, preflight=False):
    report = {'schema': 'pc.api-only-release-result.v1', 'result': 'HOLD', 'reason': 'UNVERIFIED',
              'target_sha': intent.get('target_sha') if type(intent) is dict and type(intent.get('target_sha')) is str and SHA.fullmatch(intent['target_sha']) else None,
              'api_image_updated': False, 'runtime_state':'NOT_OBSERVED',
              'baseline_filesystem_attestation':'NOT_PROVEN', 'rollback': 'NOT_ATTEMPTED', 'business_data_rollback': 'NOT_PERFORMED',
              'registration_accepted': False, 'bank_accepted': False, 'fgis_accepted': False,
              'full_dr_accepted': False, 'deployment_authorized': False}
    armed = False
    baseline = None
    journal = False
    lease = contextlib.ExitStack()
    try:
        validate_intent(intent, host.now())
        host.admitted_reference(intent)
        lease.enter_context(host.lock())
        baseline = host.snapshot(intent)
        report['runtime_state']='BASELINE_OBSERVED'
        demand(baseline['revision'] == intent['baseline_sha'] and
               baseline['image_id'] == intent['baseline_image_id'] and baseline['ready'] is True,
               'CANONICAL_BASELINE_CHANGED')
        host.assert_baseline_publication(intent,baseline)
        demand(host.effective_api_image_id() == baseline['image_id'], 'BASELINE_COMPOSE_IMAGE_MISMATCH')
        host.assert_current(intent, baseline)
        host.capacity(intent)
        db = host.database(intent, baseline)
        demand(db.get('database_compatibility') == 'VERIFIED_TARGET_CONTRACT' and
               db.get('catalog_match') is True and db.get('principals_match') is True and
               db.get('migration_match') is True and db.get('both_clients_bound') is True,
               'DATABASE_COMPATIBILITY_NOT_PROVEN')
        host.assert_current(intent, baseline)
        host.public_smoke(intent)
        if preflight:
            report.update(result='PREFLIGHT_ONLY', reason='NONE')
            return report
        # Reservation is durable and exclusive BEFORE any image, backup or
        # configuration mutation. Interrupted/failed operations are never reset.
        host.journal_begin(intent, baseline)
        journal = True
        host.journal_write('PREPARING')
        backup = host.backup(intent, baseline)
        demand(backup.get('classification') == 'CRITICAL_STATE_RESTORE_VERIFIED_NOT_RELEASE_ACCEPTANCE' and
               backup.get('target_sha') == intent['target_sha'] and backup.get('disposable_cleanup') == 'VERIFIED' and
               backup.get('source_mutation') == 'NONE' and backup.get('deployment_authorized') is False,
               'BACKUP_RESTORE_NOT_PROVEN')
        host.assert_current(intent, baseline)
        host.capacity(intent)
        image_id = host.pull(intent['api_digest'], intent['target_sha'])
        demand(type(image_id) is str and IMAGE_ID.fullmatch(image_id), 'TARGET_IMAGE_ID_INVALID')
        host.assert_current(intent, baseline)
        demand(host.now() <= intent['expires'], 'FINITE_WINDOW_EXPIRED')
        host.journal_write('API_MUTATION_ARMED')
        # An override write can fail after rename/fsync: arm first.
        armed = True
        report['runtime_state']='UNKNOWN_DURING_TRANSITION'
        host.write_override(intent['api_digest'])
        host.recreate_api()
        current = host.wait_api()
        verify_runtime(baseline, current, image_id, intent['target_sha'])
        demand(current['api_id'] != baseline['api_id'], 'API_NOT_RECREATED')
        demand(host.effective_api_image_id() == image_id, 'PERSISTED_IMAGE_BINDING_FAILED')
        # Rebind BOTH target image clients; a healthy HTTP process alone
        # cannot establish that AuthPrisma still resolves the intended DB.
        after_db = host.database(intent, current)
        demand(after_db == db, 'TARGET_DATABASE_CONTRACT_CHANGED')
        host.public_smoke(intent)
        host.journal_write('API_IMAGE_VERIFIED')
        armed = False
        report.update(result='API_IMAGE_RELEASE_VERIFIED', reason='NONE', api_image_updated=True,runtime_state='TARGET_IMAGE_VERIFIED')
        return report
    except BaseException as error:
        code = str(error) if type(error) is ReleaseError and re.fullmatch(r'[A-Z0-9_]{1,80}', str(error)) else 'EXECUTION_UNAVAILABLE'
        report['reason'] = code
        if armed and baseline is not None:
            # Never delegate to the legacy tag-based rollback executor.
            report['rollback'] = 'ATTEMPTED'
            try:
                with contextlib.suppress(BaseException):
                    host.journal_write('ROLLBACK_ARMED')
                host.write_override(baseline['image_id'])
                host.recreate_api()
                restored = host.wait_api()
                verify_runtime(baseline, restored, baseline['image_id'], baseline['revision'])
                host.restore_override(baseline['override'])
                demand(host.effective_api_image_id() == baseline['image_id'], 'ORIGINAL_COMPOSE_REFERENCE_DRIFT')
                # Recreate once from the byte-restored original file list, so
                # Compose authority labels do not retain a now-absent override.
                host.recreate_api()
                final = host.wait_api()
                verify_runtime(baseline, final, baseline['image_id'], baseline['revision'])
                demand(final['override'] == baseline['override'], 'ORIGINAL_OVERRIDE_NOT_RESTORED')
                demand(host.database(intent,final)==db,'RESTORED_DATABASE_CONTRACT_NOT_PROVEN')
                host.public_smoke(intent)
                host.journal_write('ROLLED_BACK_API_IMAGE_ONLY')
                report.update(result='ROLLED_BACK_API_IMAGE_ONLY', rollback='VERIFIED',runtime_state='BASELINE_IMAGE_VERIFIED')
            except BaseException:
                report.update(result='RECONCILIATION_REQUIRED', rollback='NOT_PROVEN',runtime_state='UNKNOWN_RECONCILIATION_REQUIRED')
                with contextlib.suppress(BaseException):
                    host.journal_write('UNKNOWN_ROLLBACK_REQUIRES_RECONCILIATION')
        elif journal:
            with contextlib.suppress(BaseException):
                host.journal_write('HOLD_BEFORE_API_MUTATION')
        return report
    finally:
        # Success is written before closing; a kill/transport loss leaves the
        # exclusive journal present and cannot authorize an automatic retry.
        with contextlib.suppress(BaseException):
            lease.close()
        with contextlib.suppress(BaseException):
            host.close()


def bounded(argv, *, data=None, timeout=30, limit=MAX_OUTPUT, cwd='/', process_env=None):
    demand(type(argv) is list and argv and all(type(v) is str and '\0' not in v for v in argv), 'COMMAND_PROFILE')
    child = subprocess.Popen(argv, stdin=subprocess.PIPE if data is not None else subprocess.DEVNULL,
                             stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, env=ENV if process_env is None else process_env,
                             start_new_session=True, cwd=cwd)
    output = bytearray()
    deadline = time.monotonic() + timeout
    try:
        demand(data is None or type(data) is bytes and len(data) <= MAX_OUTPUT, 'INPUT_BOUND')
        offset = 0
        with selectors.DefaultSelector() as selector:
            os.set_blocking(child.stdout.fileno(), False)
            selector.register(child.stdout, selectors.EVENT_READ, 'stdout')
            if data is not None:
                os.set_blocking(child.stdin.fileno(), False)
                if data:
                    selector.register(child.stdin, selectors.EVENT_WRITE, 'stdin')
                else:
                    child.stdin.close()
            while selector.get_map():
                remaining = deadline - time.monotonic()
                demand(remaining > 0, 'COMMAND_TIMEOUT')
                events = selector.select(min(0.25, remaining))
                for key, _ in events:
                    if key.data == 'stdin':
                        try:
                            count = os.write(key.fileobj.fileno(), memoryview(data)[offset:offset + 65536])
                        except (BrokenPipeError, OSError):
                            raise ReleaseError('COMMAND_INPUT_FAILED') from None
                        demand(count > 0, 'COMMAND_INPUT_FAILED')
                        offset += count
                        if offset == len(data):
                            selector.unregister(key.fileobj)
                            child.stdin.close()
                    else:
                        part = os.read(key.fileobj.fileno(), min(65536, limit + 1 - len(output)))
                        if not part:
                            selector.unregister(key.fileobj)
                        else:
                            output.extend(part)
                            demand(len(output) <= limit, 'COMMAND_OUTPUT_BOUND')
            while True:
                status = os.waitid(os.P_PID, child.pid, os.WEXITED | os.WNOWAIT | os.WNOHANG)
                if status is not None:
                    demand(status.si_code == os.CLD_EXITED and status.si_status == 0, 'COMMAND_FAILED')
                    return bytes(output)
                demand(time.monotonic() < deadline, 'COMMAND_TIMEOUT')
                time.sleep(0.01)
    finally:
        # Kill/reap the owned group before its leader PID can be recycled.
        with contextlib.suppress(ProcessLookupError):
            os.killpg(child.pid, signal.SIGKILL)
        child.wait(timeout=5)
        child.stdout.close()
        if child.stdin is not None:
            child.stdin.close()


def directory(path):
    demand(type(path) is str and path.startswith('/') and '\0' not in path and
           all(p not in ('', '.', '..') for p in path.split('/')[1:]), 'DIRECTORY_PROFILE')
    fd = os.open('/', os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    try:
        for part in path.split('/')[1:]:
            info = os.fstat(fd)
            demand(info.st_uid == 0 and not stat.S_IMODE(info.st_mode) & 0o022, 'DIRECTORY_OWNER_MODE')
            child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=fd)
            os.close(fd)
            fd = child
        info = os.fstat(fd)
        demand(info.st_uid == 0 and not stat.S_IMODE(info.st_mode) & 0o022, 'DIRECTORY_OWNER_MODE')
        return fd
    except BaseException:
        os.close(fd)
        raise


def file_read(path, *, optional=False, limit=1024 * 1024):
    parent, name = str(path).rsplit('/', 1)
    fd = directory(parent)
    try:
        try:
            handle = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC | os.O_NOATIME, dir_fd=fd)
        except FileNotFoundError:
            demand(optional, 'PROTECTED_FILE_MISSING')
            return None
        try:
            before = os.fstat(handle)
            demand(stat.S_ISREG(before.st_mode) and before.st_uid == 0 and
                   not stat.S_IMODE(before.st_mode) & 0o022 and before.st_nlink == 1 and
                   0 <= before.st_size <= limit, 'PROTECTED_FILE_PROFILE')
            raw = bytearray()
            while len(raw) <= limit:
                chunk = os.read(handle, min(65536, limit + 1 - len(raw)))
                if not chunk:
                    break
                raw.extend(chunk)
            after = os.fstat(handle)
            token = lambda s: (s.st_dev, s.st_ino, s.st_size, s.st_mtime_ns, s.st_ctime_ns)
            demand(len(raw) == before.st_size and token(before) == token(after), 'PROTECTED_FILE_CHANGED')
            return {'bytes': bytes(raw), 'mode': stat.S_IMODE(before.st_mode), 'uid': before.st_uid, 'gid': before.st_gid}
        finally:
            os.close(handle)
    finally:
        os.close(fd)



def protected_sha256(path, expected):
    parent, name = str(path).rsplit('/', 1)
    fd = directory(parent)
    handle = None
    try:
        handle = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NOATIME | os.O_NONBLOCK, dir_fd=fd)
        before = os.fstat(handle)
        demand(stat.S_ISREG(before.st_mode) and before.st_uid == 0 and before.st_nlink == 1 and
               not stat.S_IMODE(before.st_mode) & 0o077 and 0 < before.st_size <= 2 * 1024**3,
               'PRESERVED_FILE_PROFILE')
        hasher, count, deadline = hashlib.sha256(), 0, time.monotonic() + 60
        while True:
            demand(time.monotonic() < deadline, 'PRESERVED_HASH_TIMEOUT')
            part = os.read(handle, 65536)
            if not part:
                break
            count += len(part)
            demand(count <= before.st_size, 'PRESERVED_FILE_CHANGED')
            hasher.update(part)
        after = os.fstat(handle)
        token = lambda x: (x.st_dev, x.st_ino, x.st_size, x.st_mtime_ns, x.st_ctime_ns)
        demand(count == before.st_size and token(before) == token(after) and hasher.hexdigest() == expected,
               'PRESERVED_CIPHERTEXT_CHANGED')
    finally:
        if handle is not None:
            os.close(handle)
        os.close(fd)


def atomic_file(parent, name, value):
    fd = directory(parent)
    temporary = None
    try:
        demand('/' not in name and name not in ('', '.', '..'), 'OUTPUT_NAME')
        # All writes go through an owned directory; no-follow existing targets.
        try:
            old = os.stat(name, dir_fd=fd, follow_symlinks=False)
            demand(stat.S_ISREG(old.st_mode) and old.st_uid == 0 and old.st_nlink == 1, 'OUTPUT_TARGET_PROFILE')
        except FileNotFoundError:
            pass
        temporary = '.pc-api-write-' + os.urandom(16).hex()
        handle = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=fd)
        try:
            raw = value['bytes']
            demand(type(raw) is bytes and len(raw) <= 1024 * 1024, 'OUTPUT_BOUND')
            offset = 0
            while offset < len(raw):
                n = os.write(handle, raw[offset:])
                demand(n > 0, 'OUTPUT_WRITE')
                offset += n
            os.fchown(handle, value['uid'], value['gid'])
            os.fchmod(handle, value['mode'])
            os.fsync(handle)
        finally:
            os.close(handle)
        os.rename(temporary, name, src_dir_fd=fd, dst_dir_fd=fd)
        temporary = None
        os.fsync(fd)
    finally:
        if temporary is not None:
            with contextlib.suppress(FileNotFoundError):
                os.unlink(temporary, dir_fd=fd)
        os.close(fd)



def env_map(value):
    if value is None:
        return {}
    if type(value) is dict:
        demand(all(type(k) is str and type(v) is str for k,v in value.items()),'ENVIRONMENT_PROFILE')
        return value
    demand(type(value) is list and len(value)<=4096,'ENVIRONMENT_PROFILE')
    result={}
    for item in value:
        demand(type(item) is str and '=' in item,'ENVIRONMENT_PROFILE')
        key,part=item.split('=',1)
        demand(key not in result and re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]{0,127}',key),'ENVIRONMENT_PROFILE')
        result[key]=part
    return result




def compose_structural_view(raw):
    """Mask literal/folded block scalar bodies, preserving original renderer bytes."""
    demand(type(raw) is bytes and 0<len(raw)<=1024*1024,'COMPOSE_INPUT_BOUND')
    text=raw.decode('utf-8','strict')
    # Encoded keys and line-continued quoted keys are outside this closed
    # profile. A scalar body itself is opaque and cannot add YAML inputs.
    output=[];scalar_indent=None
    for line in text.splitlines(keepends=True):
        content=line.rstrip('\r\n');indent=len(content)-len(content.lstrip(' '))
        if scalar_indent is not None:
            if not content.strip() or indent>scalar_indent:
                output.append('\n' if line.endswith('\n') else '')
                continue
            scalar_indent=None
        demand(not content.startswith('\t'),'COMPOSE_EXTERNAL_PROFILE')
        # A multiline quoted scalar is deliberately unsupported rather than
        # confusing its continuation with an env_file mapping. Apostrophes
        # within plain words are ordinary scalar characters.
        q=0
        while q<len(content):
            ch=content[q]
            if ch=='#' and (q==0 or content[q-1].isspace()):break
            if ch in ('"',"'") and (q==0 or content[q-1].isspace() or content[q-1] in ':,-[{'):
                quote=ch;q+=1;closed=False
                while q<len(content):
                    if quote=='"' and content[q]=='\\':q+=2;continue
                    if content[q]==quote:
                        if quote=="'" and q+1<len(content) and content[q+1]=="'":q+=2;continue
                        closed=True;q+=1;break
                    q+=1
                demand(closed,'COMPOSE_MULTILINE_QUOTED_PROFILE')
            else:q+=1
        output.append(line)
        header=re.search(r'(?:^ *|: *|^ *- +)[>|](?:[1-9][+-]?|[+-][1-9]?|[+-]?) *(?:#.*)?$',content)
        if header:
            scalar_indent=indent
        elif re.search(r'(?:^ *|: *|^ *- +)[>|]',content):
            raise ReleaseError('COMPOSE_BLOCK_SCALAR_PROFILE')
    return ''.join(output)


def validate_compose_input_profile(raw):
    """Admit literal block YAML only; reject hidden transitive inputs before rendering."""
    demand(type(raw) is bytes and 0<len(raw)<=1024*1024,'COMPOSE_INPUT_BOUND')
    text=compose_structural_view(raw)
    demand('\0' not in text and '\ufeff' not in text and
           re.search(r'\\(?:[uUxX]|\r?\n)',text) is None,'COMPOSE_EXTERNAL_PROFILE')
    external=r"(?:include|extends|label_file|secrets|configs|provider)"
    demand(re.search(r"(?im)(?:^|[{},\n])\s*(?:"+external+r"|[\"']"+external+r"[\"'])\s*:",text) is None,
           'COMPOSE_EXTERNAL_PROFILE')
    demand(re.search(r'(?m)^\s*(?:[!?%]|<<\s*:)',text) is None,'COMPOSE_EXTERNAL_PROFILE')
    # Strip quoted scalars and comments before looking for YAML operators.
    # Values use captured explicit/default env files; env_file interpolation
    # itself is rejected by the separate literal parser.
    plain=re.sub(r'"(?:[^"\\\r\n]|\\.)*"|\'(?:[^\'\r\n]|\'\')*\'','""',text)
    plain=re.sub(r'(?m)(?:^|\s)#.*$','',plain)
    plain=re.sub(r'\$\{[^{}\r\n]*\}','VALUE',plain)
    demand(re.search(r'(?<![A-Za-z0-9_./-])[&*][A-Za-z0-9_-]+',plain) is None,
           'COMPOSE_EXTERNAL_PROFILE')
    # Empty reset/override collections contain no transitive input.
    plain=re.sub(r'\[\s*\]|\{\s*\}','',plain)
    demand(not any(v in plain for v in '{}[]'),'COMPOSE_EXTERNAL_PROFILE')
    demand(re.search(r'!(?!reset\b|override\b)',plain) is None,'COMPOSE_EXTERNAL_PROFILE')


def declared_env_files(raw, parent):
    """Closed literal env_file profile; capture every byte before Compose reads it."""
    validate_compose_input_profile(raw)
    text=compose_structural_view(raw)
    demand(not any(x in text for x in ('\\\\u','\\\\x','\\\\\n','\\\\\r\n')),'COMPOSE_EXTERNAL_PROFILE')
    rows=text.splitlines()
    result=[]
    def admit(value):
        value=value.strip()
        if len(value)>=2 and value[0]==value[-1] and value[0] in "'\"":
            value=value[1:-1]
        demand(re.fullmatch(r'[A-Za-z0-9_./-]{1,4096}',value) and
               all(p not in ('.','..','') for p in value.lstrip('/').split('/')),'ENV_FILE_PROFILE')
        result.append(value if value.startswith('/') else str(Path(parent)/value))
    for index,line in enumerate(rows):
        match=re.fullmatch(r"(\s*)(?:env_file|\"env_file\"|'env_file')\s*:\s*(.*?)\s*",line)
        if not match:
            continue
        if match[2]:
            admit(match[2])
        else:
            count=0
            for row in rows[index+1:]:
                if not row.strip() or row.lstrip().startswith('#'):
                    continue
                if len(row)-len(row.lstrip())<=len(match[1]):
                    break
                item=re.fullmatch(r'\s*-\s+(.+?)\s*',row)
                demand(item is not None,'ENV_FILE_PROFILE')
                admit(item[1]);count+=1
            demand(count>0,'ENV_FILE_PROFILE')
    return result


