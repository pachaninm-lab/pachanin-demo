def bind_window(rows, target, command, now):
    demand(type(rows) is list and len(rows)<=1000 and SHA.fullmatch(target) and
           re.fullmatch(r'[1-9][0-9]{0,19}',command),'WINDOW_INPUT')
    matched=[]
    prefix='PC_API_ONLY_HOST_WINDOW\n'
    for row in rows:
        if row.get('user',{}).get('login')!='pachaninm-lab' or row.get('author_association')!='OWNER':
            continue
        body=row.get('body','')
        if type(body) is not str or not body.startswith(prefix):
            continue
        candidate=closed_json(body[len(prefix):].encode())
        if candidate.get('target_sha')!=target or candidate.get('operation_id')!=command:
            continue
        demand(row['created_at']==row['updated_at'],'WINDOW_EDITED')
        expected={'owner','target_sha','operation_id','not_before','expires','source_accepted',
                  'native_accepted','legacy_operations_fenced','original_volume_inventory_sha256'}
        demand(set(candidate)==expected,'WINDOW_PROFILE')
        demand(candidate['owner']=='pachaninm-lab' and
               all(candidate[k] is True for k in ('source_accepted','native_accepted','legacy_operations_fenced')) and
               type(candidate['not_before']) is int and type(candidate['expires']) is int and
               candidate['not_before']<=now<=candidate['expires'] and
               0<candidate['expires']-candidate['not_before']<=1200 and
               type(candidate['original_volume_inventory_sha256']) is str and
               HASH.fullmatch(candidate['original_volume_inventory_sha256']),'FINITE_WINDOW_NOT_PROVEN')
        matched.append({**candidate,'claim_id':str(row['id'])})
    demand(len(matched)>0,'FINITE_WINDOW_NOT_YET_POSTED')
    demand(len(matched)==1,'UNIQUE_FINITE_WINDOW_REQUIRED')
    return matched[0]



