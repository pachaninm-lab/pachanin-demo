def acquire_baseline_publication(observed,execute=None):
    """Runner-only registry acquisition from the actual host's immutable RepoDigests.

    An old mutable SHA tag is not consulted. Missing observation is NOT_PROVEN,
    not evidence of absence. This proves the image config, not a writable
    running container filesystem or full application/data integrity.
    """
    if execute is None:
        execute=bounded
    demand(type(observed) is dict and type(observed.get('image_id')) is str and
           IMAGE_ID.fullmatch(observed['image_id']) and type(observed.get('revision')) is str and
           SHA.fullmatch(observed['revision']),'BASELINE_IMAGE_OBSERVATION_NOT_PROVEN')
    refs=observed.get('registry_digests')
    demand(type(refs) is list and len(refs)<=32 and all(type(v) is str for v in refs),
           'BASELINE_REPODIGEST_NOT_PROVEN')
    selected=[v for v in refs if DIGEST.fullmatch(v)]
    demand(len(selected)>0,'BASELINE_REPODIGEST_NOT_PROVEN')
    demand(len(selected)==1,'BASELINE_REPODIGEST_AMBIGUOUS')
    reference=selected[0]
    home=os.environ.get('HOME','')
    demand(home.startswith('/'),'RUNNER_DOCKER_AUTH_PROFILE')
    docker=DOCKER+['--config',str(Path(home)/'.docker')]
    execute(docker+['pull',reference],timeout=180)
    rows=closed_json(execute(docker+['image','inspect',reference],timeout=15))
    demand(type(rows) is list and len(rows)==1,'BASELINE_REGISTRY_CONFIG_NOT_PROVEN')
    image=rows[0];labels=(image.get('Config') or {}).get('Labels') or {}
    demand(image.get('Id')==observed['image_id'] and
           labels.get('org.opencontainers.image.revision')==observed['revision'] and
           labels.get('org.opencontainers.image.source')=='https://github.com/pachaninm-lab/pachanin-demo' and
           reference in (image.get('RepoDigests') or []),'BASELINE_PUBLISHED_IMAGE_MISMATCH')
    return {'schema':'pc.api-only-baseline-publication.v1','api_digest':reference,'image_id':image['Id'],
            'revision':observed['revision'],'source':labels['org.opencontainers.image.source'],
            'verification':'CANONICAL_DIGEST_CONFIG_MATCH'}


