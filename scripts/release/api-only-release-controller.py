# A semantic label replaces a varying migration-owner/runtime role name.
# Other source-defined authority names remain exact, so an unexpected grant or
# membership is never collapsed into an anonymous identical placeholder. Raw
# catalog records stay in the protected process and are not public evidence.
ROLE_CTE = r"""
WITH role_alias AS (
 SELECT oid, CASE
  WHEN oid=(SELECT relowner FROM pg_class WHERE oid='public._prisma_migrations'::regclass)
   THEN 'MIGRATION_OWNER'
  WHEN rolname=$1::text THEN 'DEAL_RUNTIME'
  WHEN rolname=$2::text THEN 'AUTH_RUNTIME'
  ELSE 'NAMED:'||rolname END AS label
 FROM pg_roles
)
"""


def role_label(expression):
    return "CASE WHEN " + expression + "=0 THEN 'PUBLIC' ELSE (SELECT label FROM role_alias WHERE oid=" + expression + ") END"


