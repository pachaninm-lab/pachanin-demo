def runtime_fingerprint(row):
    config = dict(row['Config'])
    # Image and Compose bookkeeping differ intentionally. Every environment,
    # security/resource/mount/command policy still participates.
    config.pop('Image', None)
    if config.get('Hostname') == row['Id'][:12]:
        config.pop('Hostname', None)
    labels = dict(config.get('Labels') or {})
    for key in list(labels):
        if (key.startswith('org.opencontainers.image.') or key in
            ('com.docker.compose.config-hash', 'com.docker.compose.image',
             'com.docker.compose.replace', 'com.docker.compose.project.config_files')):
            labels.pop(key, None)
    config['Labels'] = labels
    host = dict(row['HostConfig'])
    host.pop('ContainerIDFile', None)
    network = row['NetworkSettings'].get('Networks') or {}
    mounts = [{k: m.get(k) for k in ('Type', 'Source', 'Destination', 'Mode', 'RW', 'Propagation', 'Name', 'Driver')}
              for m in row.get('Mounts', [])]
    return digest({'config': config, 'host': host, 'networks': sorted(network),
                   'mounts': sorted(mounts, key=lambda m: m['Destination'])})



