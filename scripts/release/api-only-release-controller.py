def source_migrations(target):
    demand(type(target) is str and SHA.fullmatch(target),'TARGET_SHA')
    env={**ENV,'GIT_CONFIG_NOSYSTEM':'1','GIT_CONFIG_GLOBAL':'/dev/null',
         'GIT_NO_LAZY_FETCH':'1','GIT_ALLOW_PROTOCOL':'','GIT_PROTOCOL_FROM_USER':'0',
         'GIT_NO_REPLACE_OBJECTS':'1','GIT_GRAFT_FILE':'/dev/null'}
    def git(args):
        return bounded(['/usr/bin/git','--no-optional-locks','-c','core.hooksPath=/dev/null',
                        '-c','core.fsmonitor=false','-c','protocol.allow=never',*args],
                       process_env=env,cwd=str(Path(__file__).resolve().parents[2]),timeout=10)
    raw=git(['ls-tree','-r','-z',target,'--','apps/api/prisma/migrations/'])
    demand(raw.endswith(b'\0'),'SOURCE_TREE_FRAMING')
    result={}
    for entry in raw[:-1].split(b'\0'):
        header,path=entry.split(b'\t',1); path=path.decode('utf-8','strict')
        match=re.fullmatch(r'apps/api/prisma/migrations/([A-Za-z0-9][A-Za-z0-9_-]{0,254})/migration\.sql',path)
        if match:
            demand(re.fullmatch(rb'100644 blob [0-9a-f]{40}',header) and match[1] not in result,'SOURCE_MIGRATION_PROFILE')
            result[match[1]]=hashlib.sha256(git(['show',target+':'+path])).hexdigest()
        else:
            demand(path=='apps/api/prisma/migrations/migration_lock.toml','UNEXPECTED_MIGRATION_SOURCE')
    demand(0<len(result)<=5000,'SOURCE_MIGRATION_SET')
    return dict(sorted(result.items()))


