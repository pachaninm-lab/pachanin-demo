class ReleaseError(Exception):
    """Only these fixed codes are public."""


def demand(value, code):
    if not value:
        raise ReleaseError(code)


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=True).encode()


def digest(value):
    return hashlib.sha256(canonical(value)).hexdigest()


def closed_json(raw):
    def unique(items):
        demand(len(items) == len(dict(items)), 'DUPLICATE_JSON_KEY')
        return dict(items)
    try:
        demand(type(raw) is bytes and 0 < len(raw) <= MAX_OUTPUT, 'JSON_BOUND')
        return json.loads(raw.decode('utf-8', errors='strict'), object_pairs_hook=unique,
                          parse_constant=lambda _: (_ for _ in ()).throw(ReleaseError('JSON_CONSTANT')))
    except (ValueError, UnicodeError, RecursionError):
        raise ReleaseError('JSON_INVALID') from None


