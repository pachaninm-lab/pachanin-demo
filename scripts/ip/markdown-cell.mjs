// Экранирование ячейки markdown-таблицы, собираемой из внешнего текста.
//
// Отдельный модуль, потому что этим пользуются два генератора документов, а
// разошедшиеся копии экранирования — это способ починить одну и оставить
// вторую. Модуль чистый: импортируется без побочных эффектов и проверяется
// тестами.
//
// Что здесь внешнее. Имя автора приходит из `git log --format=%aN`, то есть
// его выбирает тот, кто делает коммит. Описание коммита — тем более. Оба
// попадают в таблицы приложения к договору об отчуждении и в досье due
// diligence, где строка таблицы заявляет, чьи права не оформлены и какие
// произведения передаются.
//
// Замерено на строке, где должно быть 6 ячеек, при экранировании одной только
// трубы (`replace(/\|/g, '\\|')`):
//
//   слеш вплотную к трубе   7 ячеек   — `a\|B|C` даёт `a\\|B|C`, и рендерер
//                                       читает `\\` как экранированный слеш,
//                                       а следующую трубу — как разделитель
//   две трубы после слеша   7 ячеек
//   перевод строки          2 строки
//   возврат каретки         2 строки

/**
 * Порядок шагов обязателен и каждый из них нужен:
 *
 *  1. переводы строк — первыми, иначе ячейка становится новой строкой таблицы;
 *  2. срез — ДО экранирования, иначе он режет экранирующую последовательность
 *     пополам и оставляет висящий слеш, который экранирует закрывающую трубу;
 *  3. слеши — раньше труб, иначе добавленный на шаге 4 слеш сам окажется
 *     экранирован;
 *  4. трубы.
 */
export function markdownCell(value, limit = 100) {
  return String(value ?? '')
    .replace(/[\r\n]+/gu, ' ')
    .slice(0, limit)
    .replace(/\\/gu, '\\\\')
    .replace(/\|/gu, '\\|');
}

/**
 * Сколько ячеек увидит рендерер: труба считается разделителем, только если
 * перед ней чётное число слешей. Наивный `split('|')` считает и экранированные,
 * поэтому объявляет корректные строки сломанными — на этом уже один раз был
 * сделан неверный вывод.
 */
export function renderedCellCount(row) {
  let cells = 1;
  let backslashes = 0;
  for (const character of String(row)) {
    if (character === '\\') {
      backslashes += 1;
      continue;
    }
    if (character === '|' && backslashes % 2 === 0) cells += 1;
    backslashes = 0;
  }
  return cells;
}
